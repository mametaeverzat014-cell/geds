// ─── offline snapshot fallback ──────────────────────────────────────────────
//
// The backend sleeps after 15 min on free-tier hosting and takes 20-30 s to
// wake. Nearly every panel renders `null` until its fetch resolves, so someone
// arriving at a cold instance used to see a title and empty space, with no
// signal the page would ever fill in.
//
// So the build ships `public/snapshot/*.json`: the exact responses the
// deterministic endpoints return on this commit, generated by
// backend/scripts/build_frontend_snapshot.py and pinned by
// backend/tests/test_frontend_snapshot.py, which fails if the committed files
// drift from what the API actually returns.
//
// When a live call fails — network error OR non-2xx — the client serves the
// snapshot, flips `snapshotActive`, and the connection banner states plainly
// that the numbers on screen are precomputed and names the commit. Nothing is
// invented and nothing is silently substituted: it is the same model output,
// arriving from disk instead of over the wire, and labelled as such.
//
// Endpoints whose answers depend on wall-clock time or on an LLM are NOT
// snapshotted, so those panels stay empty while the backend is down. A frozen
// "current news signal" or "last refreshed" would be a false claim, which is
// worse than a blank panel.

/** Request path -> snapshot filename stem. Must stay byte-identical to `slug()`
 *  in backend/scripts/build_frontend_snapshot.py; a test pins the two together. */
export function snapshotKey(path: string): string {
  return path.replace(/^\/+|\/+$/g, "").replace(/[^a-zA-Z0-9._-]+/g, "_");
}

let snapshotActive = false;
const snapshotListeners = new Set<() => void>();

/** True once any response on this page has been served from the static snapshot. */
export const isSnapshotActive = () => snapshotActive;
export const isSnapshotActiveServer = () => false;

export function subscribeSnapshot(fn: () => void): () => void {
  snapshotListeners.add(fn);
  return () => { snapshotListeners.delete(fn); };
}

async function fromSnapshot<T>(key: string): Promise<T> {
  const res = await fetch(`/snapshot/${key}.json`);
  if (!res.ok) throw new Error(`snapshot ${key} → ${res.status}`);
  const data = (await res.json()) as T;
  if (!snapshotActive) {
    snapshotActive = true;
    snapshotListeners.forEach((fn) => fn());
  }
  return data;
}

