async function getJson<T>(path: string): Promise<T> {
  try {
    const res = await fetch(`${API}${path}`);
    if (!res.ok) throw new Error(`GET ${path} → ${res.status}`);
    return (await res.json()) as T;
  } catch (err) {
    // Rethrow the ORIGINAL error when no snapshot covers this path, so a
    // caller's catch block still sees why the live call failed rather than a 404
    // on a file that was never meant to exist.
    return fromSnapshot<T>(snapshotKey(path)).catch(() => { throw err; });
  }
}

async function postJson<T>(path: string, body: unknown): Promise<T> {
  try {
    const res = await fetch(`${API}${path}`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body),
    });
    if (!res.ok) throw new Error(`POST ${path} → ${res.status}`);
    return (await res.json()) as T;
  } catch (err) {
    // Only baked scenarios have an honest precomputed answer. A custom scenario
    // must never be served someone else's cascade.
    const sid = (body as { scenario_id?: unknown } | null)?.scenario_id;
    if (typeof sid !== "string") throw err;
    return fromSnapshot<T>(`post_${snapshotKey(path)}__${snapshotKey(sid)}`)
      .catch(() => { throw err; });
  }
}

/** GET through the snapshot-aware client. For endpoints with no typed helper. */
export const getRaw = <T,>(path: string): Promise<T> => getJson<T>(path);

async function deleteJson<T>(path: string): Promise<T> {
  const res = await fetch(`${API}${path}`, { method: "DELETE" });
  if (!res.ok) throw new Error(`DELETE ${path} → ${res.status}`);
  return res.json();
}

