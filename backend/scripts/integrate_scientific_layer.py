def _load_country_sectors() -> tuple[tuple[CountrySector, ...], dict[str, set[str]]]:
    rows = _load("country_sector_presence.csv")
    out = []
    by_country: dict[str, set[str]] = {}
    for r in rows:
        cs = CountrySector(
            country_iso3=r.get("country_iso3", ""),
            sector=r.get("sector", ""),
            present=r.get("present", "false").lower() == "true",
            source_origin=r.get("_source_origin", ""),
        )
        out.append(cs)
        if cs.present:
            by_country.setdefault(cs.country_iso3, set()).add(cs.sector)
    return tuple(out), by_country


