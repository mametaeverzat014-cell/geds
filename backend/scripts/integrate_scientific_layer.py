def _f(s) -> float | None:
    if s in (None, "", "—"):
        return None
    try:
        return float(s)
    except (ValueError, TypeError):
        return None


def _i(s) -> int | None:
    v = _f(s)
    return int(v) if v is not None else None


def _load(name: str) -> list[dict]:
    p = _CSV_DIR / name
    if not p.exists():
        return []
    with p.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


