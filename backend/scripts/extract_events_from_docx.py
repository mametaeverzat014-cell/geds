    raw = json.loads(DUMP.read_text(encoding="utf-8"))
    paragraphs: list[str] = raw["paragraphs"]
    tables: list[list[list[str]]] = raw["tables"]

    # Build (event_id -> source-data) map.
    events: dict[int, dict] = {}

    # Phase 1: 30 detail tables = events 1-30
    detail_tables = tables[:30]
    # Find event headings in paragraphs to pair with detail tables
    event_heading_re = re.compile(r"Event\s+(\d+)\s*[—–-]\s*(.+)")
    heading_names: dict[int, str] = {}
    for p in paragraphs:
        if m := event_heading_re.match(p.strip()):
            heading_names[int(m.group(1))] = m.group(2).strip()

    for i, tbl in enumerate(detail_tables, start=1):
        d = parse_detail_table(tbl)
        d["_event_id"] = i
        d["_name_from_heading"] = heading_names.get(i, "")
        d["_source"] = "detail_table"
        events[i] = d

    # Phase 2: paragraph-only events 31-42 (one paragraph per event of form
    # "Year: ... | Type: ... | Affected: ... | ...")
    in_event = None
    buffer: list[str] = []
    para_events: dict[int, str] = {}
    for p in paragraphs:
        if m := event_heading_re.match(p.strip()):
            # flush previous
            if in_event and in_event >= 31:
                para_events[in_event] = " ".join(buffer).strip()
            in_event = int(m.group(1))
            buffer = []
        elif in_event and p.strip():
            buffer.append(p.strip())
    if in_event and in_event >= 31:
        para_events[in_event] = " ".join(buffer).strip()

    for eid, txt in para_events.items():
        d = parse_paragraph_event(txt)
        d["_event_id"] = eid
