def parse_detail_table(table_rows: list[list[str]]) -> dict:
    """Parse a 16x2 Field|Value table."""
    out: dict[str, str] = {}
    for row in table_rows:
        if len(row) < 2:
            continue
        key, val = row[0].strip(), row[1].strip()
        if key.lower() == "field":
            continue
        out[key] = val
    return out


def parse_paragraph_event(text: str) -> dict:
    """Parse paragraph-only events 31-42 in 'Field: value | Field: value | ...' form.

    Event 42 has a trailing 'Data Quality & Limitations' postscript that must
    be stripped before splitting — it has no leading pipe and pollutes the
    last field (Source) with prose.
    """
    # Cut off any postscript after the recognised list of fields.
    for terminator in ("Data Quality & Limitations", "Recommended Citation"):
        idx = text.find(terminator)
        if idx > 0:
            text = text[:idx].strip()
            break
    out: dict[str, str] = {}
    parts = re.split(r"\s*\|\s*", text)
    for p in parts:
        p = p.strip()
        if ":" not in p:
            continue
        key, val = p.split(":", 1)
        out[key.strip()] = val.strip()
    return out


def extract_country_specific_metrics(text: str) -> list[tuple[str, str, float, str]]:
    """Find patterns like 'Greece -26%' or 'Russia GDP -3.7%' in free-text.
    Returns list of (country_iso3, metric_hint, value, note).
    """
    if not text:
        return []
    found = []
    s = text.replace("−", "-").replace("–", "-").replace("—", "-")
    # Pattern: <Country> [GDP] [<context>]? [-+]?<num>% [pp]?
    pat = re.compile(
        r"\b([A-Z][a-zA-Z]+(?:\s+[A-Z][a-zA-Z]+)?)\b[^.;|]{0,40}?([-+]?\s*\d+(?:\.\d+)?)\s*(%|pp)",
    )
    for m in pat.finditer(s):
        country_name = m.group(1)
        iso = normalize_country(country_name)
        if not iso:
            continue
        try:
            val = float(m.group(2).replace(" ", ""))
        except ValueError:
            continue
        found.append((iso, "gdp_or_trade", val, "from_freetext"))
    return found


