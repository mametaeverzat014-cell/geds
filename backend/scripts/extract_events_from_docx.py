# ── parsing helpers ────────────────────────────────────────────────────────

def normalize_country(name: str) -> str | None:
    """ISO3 lookup. Returns None if unknown (caller decides how to handle)."""
    if not name:
        return None
    k = name.strip().lower().rstrip(".").rstrip(",")
    # Strip parentheticals
    k = re.sub(r"\s*\([^)]*\)", "", k).strip()
    return COUNTRY_TO_ISO3.get(k)


def parse_country_list(raw: str) -> tuple[list[str], list[str], list[str], str]:
    """Returns (iso3_list, unmapped_names_list, expanded_regions, scope).

    scope ∈ {"country", "regional", "global"} — flag for downstream code.
    Region tokens like "EU"/"Eurozone" are expanded to representative ISO3
    members; the original term goes into `expanded_regions` for traceability.
    """
    if not raw:
        return [], [], [], "country"
    # Strip parentheticals
    raw = re.sub(r"\s*\([^)]*\)", "", raw)
    parts = re.split(r"[,;]|\sand\s|/", raw)
    iso: list[str] = []
    unmapped: list[str] = []
    expanded: list[str] = []
    scope = "country"
    for p in parts:
        p = p.strip()
        if not p:
            continue
        key = p.lower().rstrip(".").rstrip(",")
        if key in SCOPE_GLOBAL_TERMS:
            if scope != "regional":
                scope = "global"
            expanded.append(p)
            continue
        if key in REGION_TO_ISO3:
            for code in REGION_TO_ISO3[key]:
                if code not in iso:
                    iso.append(code)
            expanded.append(p)
            scope = "regional"
            continue
        code = normalize_country(p)
        if code:
            if code not in iso:
                iso.append(code)
        else:
            unmapped.append(p)
    return iso, unmapped, expanded, scope


def parse_sectors(raw: str) -> tuple[list[str], list[str]]:
    """Returns (taxonomy_sectors, unmapped_terms).
    Terms mapped to None in SECTOR_TAXONOMY are treated as filtered meta-terms
    (e.g. "all", "trade", "households") and are not counted as unmapped.
    """
    if not raw:
        return [], []
    raw = re.sub(r"\s*\([^)]*\)", "", raw)
    parts = re.split(r"[,;]|\sand\s|/", raw)
    out: list[str] = []
    unmapped: list[str] = []
    for p in parts:
        p = p.strip().lower()
        if not p:
            continue
        if p in SECTOR_TAXONOMY:
            sector = SECTOR_TAXONOMY[p]
            if sector and sector not in out:
                out.append(sector)
            # explicit None → meta-term, silently dropped
        else:
            unmapped.append(p)
    return out, unmapped


_NUM_RE = re.compile(
    r"(?P<sign>[−\-+])?\s*(?P<num>\d+(?:\.\d+)?)\s*(?:[–\-to]+\s*(?P<num2>\d+(?:\.\d+)?))?\s*(?P<pct>%|pp\b|percentage points)?",
    re.IGNORECASE,
)
# A token that looks like a year range "2003-2008" embedded in prose.
_YEAR_RANGE_RE = re.compile(r"\b(19|20)\d{2}\s*-\s*(19|20)?\d{2,4}\b")
_YEAR_RE = re.compile(r"\b(19|20)\d{2}\b")


def _is_year_match(m: re.Match) -> bool:
    """True when a numeric match looks like a year or year-range (not a percent)."""
    a = float(m.group("num"))
    b = m.group("num2")
    # Both numbers integer-valued AND in 1900-2100 → year(s)
    def _yearish(x: float) -> bool:
        return x == int(x) and 1900 <= x <= 2100
    if b is not None:
        return _yearish(a) and _yearish(float(b))
    return _yearish(a)


_INDEX_NAMES_RE = re.compile(
    r"\b(?:S&P|SP|FTSE|Nasdaq|Dow|DAX|Nikkei|Hang\s*Seng|CAC|STOXX|"
    r"BVSP|RTSI|KOSPI|TSX|ASX|MOEX|TTF)\s*\d+", re.IGNORECASE,
)


def parse_percent(raw: str) -> tuple[float | None, str]:
    """Strict parse of a percent value from prose.

    Strategy: only accept a numeric whose match group includes %, pp, or
    "percentage points". This avoids the entire class of bugs where:
      - "$275 billion" was being read as 275
      - "S&P 500" was being read as 500
      - "Nikkei 225 fell ~20%" was being read as 225 instead of 20
      - Year-range midpoints (2003-2008 → 2005.5) were being read as percent
    Returns (value, note). Notes flag ranges, currency-only text, etc.
    """
    if not raw or raw.strip().lower() in {"n/a", "na", "none", "—", "-"}:
        return None, "missing"
    s = raw.replace("–", "-").replace("—", "-").replace("−", "-")
    # Strip year tokens so they can't be picked up.
    s_clean = _YEAR_RANGE_RE.sub(" ", s)
    s_clean = re.sub(r"\b(19|20)\d{2}\b(?!\s*%)", " ", s_clean)
    # Strip stock-index names like "S&P 500", "Nikkei 225", "FTSE 100".
    s_clean = _INDEX_NAMES_RE.sub(" ", s_clean)
    has_pct_anywhere = "%" in s or "pp" in s.lower() or "percentage point" in s.lower()
    has_currency = bool(re.search(r"[$€£]\s*[\d.,]+", s))
    # Pass 1 (strict): require unit attached to the match.
    for m in _NUM_RE.finditer(s_clean):
        if _is_year_match(m):
            continue
        if not m.group("pct"):
            continue
        sign = -1.0 if m.group("sign") == "-" else 1.0
        a = float(m.group("num"))
        b = m.group("num2")
        if b:
            a = (a + float(b)) / 2.0
            note = "range_midpoint"
        else:
            note = "ok"
        return sign * a, note
    # No unit-attached number found. Be honest: don't fabricate a percent value
    # from prose with numbers in physical units (mb/d, bcm, $B, index levels…).
    # The audit will surface what the source said.
    if has_currency and not has_pct_anywhere:
        return None, "currency_only_no_pct"
    if not has_pct_anywhere:
        return None, "no_pct_unit_in_source"
    return None, "no_numeric_found"


def parse_year_range(raw: str) -> tuple[int | None, int | None]:
    """'2000–01' -> (2000, 2001), '2020–21' -> (2020, 2021), '2022–ongoing' -> (2022, None)."""
    if not raw:
        return None, None
    s = raw.replace("–", "-").replace("—", "-")
    m = re.search(r"(\d{4})(?:\s*-\s*(\d{2,4}|present|ongoing))?", s, re.IGNORECASE)
    if not m:
        return None, None
    y1 = int(m.group(1))
    y2_raw = m.group(2)
    if not y2_raw:
        return y1, y1
    if y2_raw.lower() in {"present", "ongoing"}:
        return y1, None
    y2 = int(y2_raw)
    if y2 < 100:
        y2 = (y1 // 100) * 100 + y2
    return y1, y2


_DUR_MONTHS_RE = re.compile(r"~?\s*(\d+)\+?\s*month", re.IGNORECASE)
_DUR_YEARS_RE = re.compile(r"~?\s*(\d+(?:\.\d+)?)\+?\s*year", re.IGNORECASE)
_DUR_WEEKS_RE = re.compile(r"~?\s*(\d+)\+?\s*week", re.IGNORECASE)
_DUR_DAYS_RE = re.compile(r"~?\s*(\d+)\+?\s*day", re.IGNORECASE)
_DUR_YEAR_RANGE_RE = re.compile(r"\b(19|20)(\d{2})\s*-\s*(19|20)?(\d{2,4})\b")


def parse_duration_months(raw: str) -> int | None:
    if not raw:
        return None
    s = raw.replace("–", "-").replace("—", "-")
    if m := _DUR_MONTHS_RE.search(s):
        return int(m.group(1))
    if m := _DUR_YEARS_RE.search(s):
        return int(round(float(m.group(1)) * 12))
    if m := _DUR_WEEKS_RE.search(s):
        return max(1, int(round(int(m.group(1)) / 4.345)))
    if m := _DUR_DAYS_RE.search(s):
        return max(0, int(round(int(m.group(1)) / 30.44)))
    # Fallback: year range like "2010-2015" or "2003-2008"
    if m := _DUR_YEAR_RANGE_RE.search(s):
        y1 = int(m.group(1) + m.group(2))
        end_century = m.group(3) or m.group(1)
        y2_part = m.group(4)
        y2 = int(end_century + y2_part) if len(y2_part) <= 2 else int(y2_part)
        if y2 < y1:
            y2 = (y1 // 100) * 100 + y2
        return max(1, (y2 - y1) * 12)
    return None


_RECOVERY_RE = re.compile(
    r"(?:recovery|reconstruction|rebuild(?:ing)?)\s*[:\-]?\s*(\d+(?:\.\d+)?)\+?\s*(month|year|week|day)",
    re.IGNORECASE,
)


def parse_recovery_months(raw: str) -> int | None:
    """Only return a value when the text explicitly says 'recovery: N years' or similar.
    The docx has no separate Recovery Time field; this scans Duration text for explicit
    recovery/reconstruction phrasing. Returning None means 'not stated' (audit-honest).
    """
    if not raw:
        return None
    s = raw.replace("–", "-").replace("—", "-")
    m = _RECOVERY_RE.search(s)
    if not m:
        return None
    num = float(m.group(1))
    unit = m.group(2).lower()
    if unit == "month":
        return int(num)
    if unit == "year":
        return int(round(num * 12))
    if unit == "week":
        return max(1, int(round(num / 4.345)))
    if unit == "day":
        return max(0, int(round(num / 30.44)))
    return None


def parse_confidence(raw: str) -> int | None:
    if not raw:
        return None
    m = re.search(r"\b([1-5])\b", raw)
    return int(m.group(1)) if m else None


