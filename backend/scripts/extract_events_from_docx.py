def normalize_event_type(raw: str) -> tuple[str, list[str]]:
    """Return (primary_type, secondary_types).

    Source uses combos like 'War / Sanctions (Geopolitical Disruption)'.
    Primary = first slash-separated token, normalised against the small set
    above when possible. Secondary = remaining tokens (also normalised).
    """
    if not raw:
        return "", []
    # Strip parentheticals
    cleaned = re.sub(r"\s*\([^)]*\)", "", raw).strip()
    parts = [p.strip() for p in re.split(r"[/]", cleaned) if p.strip()]
    if not parts:
        return "", []
    def _norm(t: str) -> str:
        return _TYPE_NORMALIZATION.get(t.lower(), t)
    primary = _norm(parts[0])
    secondary = [_norm(p) for p in parts[1:]]
    return primary, secondary


